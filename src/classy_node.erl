-doc false.
init(_) ->
  process_flag(trap_exit, true),
  net_kernel:monitor_nodes(
    true,
    #{ node_type => visible
     , nodedown_reason => true
     }),
  ok = classy_table:open(?tab, #{on_update => fun ?MODULE:on_ptab_update/2}),
  {ok, 1} = classy_table:ensure_tab_vsn(?tab, 1),
  ok = classy_table:open(?site_info, #{ets_options => [{read_concurrency, true}]}),
  {ok, 1} = classy_table:ensure_tab_vsn(?site_info, 1),
  classy_site_metadata:init(),
  classy_hook:foreach(?on_node_init, []),
  case init_cluster() of
    {ok, S} ->
      maybe_replay_pending_on_join_hook(S);
    {error, Reason} ->
      {stop, Reason, undefined}
  end.

-doc false.
handle_call(#call_join{} = Call, From, S) ->
  handle_join(S, From, Call);
handle_call(#call_kick{site = Target, intent = Intent}, _From, S0) ->
  case handle_kick(Target, Intent, S0) of
    {ok, S1} ->
      S = abort_post_join_hooks(S1),
      {reply, ok, S};
    {error, _} = Err ->
      {reply, Err, S0}
  end;
handle_call(#call_lock_join{pid = Pid}, _From, S0) ->
  case ensure_is_not_joining(S0) of
    ok ->
      if is_pid(Pid) ->
          {Reply, S} = do_lock_join(Pid, S0),
          {reply, Reply, S};
         true ->
          {reply, {error, badarg}, S0}
      end;
    Err ->
      {reply, Err, S0}
  end;
handle_call(#call_unlock_join{pid = Pid}, _From, S) ->
  {reply, ok, do_unlock_join(Pid, S)};
handle_call(Call, From, S) ->
  ?tp(warning, ?classy_unknown_event,
      #{ kind => call
       , from => From
       , content => Call
       , server => ?MODULE
       }),
  {reply, {error, unknown_call}, S}.

-doc false.
handle_cast(Cast, S) ->
  ?tp(warning, ?classy_unknown_event,
      #{ kind => cast
       , content => Cast
       , server => ?MODULE
       }),
  {noreply, S}.

-doc false.
handle_info(#cast_mem_deltas{} = Cast, S) ->
  handle_membership_change_event(Cast, S);
handle_info({NodeUpOrDown, _Node, _}, S) when NodeUpOrDown =:= nodeup; NodeUpOrDown =:= nodedown ->
  {noreply, update_runtime(S)};
handle_info({'EXIT', Pid, Reason}, S = #s{post_join = #post_join{worker = Pid}}) ->
  {noreply, finalize_join(Reason, S)};
handle_info(#to_auto_release_join_lock{pid = Pid}, S) ->
  {noreply, do_unlock_join(Pid, S)};
handle_info({'DOWN', MRef, process, _, _} = Info, S = #s{join_locks = JLs}) ->
  case lists:keyfind(MRef, #jl.mref, JLs) of
    #jl{pid = Pid} ->
      {noreply, do_unlock_join(Pid, S)};
    false ->
      ?tp(warning, ?classy_unknown_event,
          #{ kind => info
           , content => Info
           , server => ?MODULE
           }),
      {noreply, S}
  end;
handle_info(Info, S) ->
  ?tp(warning, ?classy_unknown_event,
      #{ kind => info
       , content => Info
       , server => ?MODULE
       }),
  {noreply, S}.

-doc false.
terminate(Reason, _S) ->
  classy_lib:is_normal_exit(Reason) orelse
    ?tp(warning, ?classy_abnormal_exit,
        #{ server => ?MODULE
         , reason => Reason
         }),
  classy_table:flush(?tab),
  classy_table:flush(?site_info),
  to_stopped(shutdown),
  persistent_term:erase(?pt_node_sets),
  persistent_term:erase(?pt_site_sets),
  persistent_term:erase(?pt_site),
  persistent_term:erase(?pt_cluster),
  classy_table:stop(?tab, 5_000),
  classy_table:stop(?site_info, 5_000),
  classy_site_metadata:terminate().

