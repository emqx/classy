%% Returns information about the local site, used for bootstrapping the remote.
-spec hello() -> bootstrap_info() | {error, _}.
hello() ->
  maybe
    {ok, Cluster} ?= the_cluster(),
    {ok, Site} ?= the_site(),
    {ok, MemData} ?= classy_membership:get_data(Cluster, Site, 0, 0),
    #{ site => Site
     , cluster => Cluster
     , mem_data => MemData
     }
  else
    undefined ->
      {error, not_in_cluster};
    Err ->
      Err
  end.

-doc false.
on_ptab_update(_, Op) ->
  case Op of
    {w, ?the_cluster, Val} ->
      persistent_term:put(?pt_cluster, Val);
    {d, ?the_cluster} ->
      persistent_term:erase(?pt_cluster);
    {w, ?the_site, Val} ->
      persistent_term:put(?pt_site, Val);
    {d, ?the_site} ->
      persistent_term:erase(?pt_site);
    _ ->
      ok
  end.

-doc false.
-spec notify_mem_deltas(classy:cluster_id(), #{classy:site() => classy_membership:update()}) -> ok.
notify_mem_deltas(Cluster, Deltas) ->
  case whereis(?SERVER) of
    undefined ->
      ok;
    Pid when is_pid(Pid) ->
      Pid ! #cast_mem_deltas{ cluster = Cluster
                            , data    = Deltas
                            },
      ok
  end.

-doc false.
prep_stop(Reason) ->
  classy_hook:foreach(?on_prep_stop, [Reason]).

-doc false.
%% Prevent the remote node from joining other nodes while the local is
%% joining.
%%
%% It's safe to call this function multiple times, only the first lock
%% will be kept for the caller process.
%%
%% Note: acquisition is mandatory: if the remote node cannot be locked
%% (for example, it is busy processing a join of its own), it may be
%% joining us or someone else at the moment, so the caller must abort
%% and retry later.
-spec lock_join_remote(node()) -> ok | {error, retry_later}.
lock_join_remote(Node) when Node =:= node() ->
  {error, locking_self};
lock_join_remote(Node) ->
  try
    %% Try to lock the joinee:
    gen_server:call(
      {?SERVER, Node},
      #call_lock_join{pid = self()},
      classy_lib:rpc_timeout())
  of
    {ok, _} ->
      ok;
    {error, _} = Err ->
      Err
  catch
    exit:{noproc, _} ->
      %% Node is not running or it's not classy-aware:
      ok;
    exit:{timeout, _} ->
      %% The remote node could be busy joining someone else, so the
      %% lock state is uncertain. The caller must retry later:
      {error, retry_later};
    _EC:Err ->
      {error, Err}
  end.

-doc false.
-spec unlock_join_remote(node(), pid()) -> ok.
unlock_join_remote(Node, Pid) ->
  Timeout = classy_lib:rpc_timeout(),
  Result = try
             gen_server:call(
               {?SERVER, Node},
               #call_unlock_join{pid = Pid},
               Timeout)
           catch
             exit:{noproc, _} ->
               %% Nothing to unlock:
               ok;
             exit:{timeout, _} ->
               {error, timeout};
             _EC:Err ->
               {error, Err}
           end,
  case Result of
    ok ->
      ok;
    {error, Reason} ->
      ?tp(warning, "Failed to release join lock",
          #{ remote => Node
           , reason => Reason
           })
  end,
  ok.

