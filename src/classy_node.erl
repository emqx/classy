-doc """
Initialize local site and cluster.

Initialization of the site ID is done as following:

@enumerate
@item If the site ID is already stored in the DB,
then it is kept as is and nothing is done.

@item If the value not stored,
and is provided as a binary argument,
then the argument is used as the new site ID.

@item If the value is not stored,
and the argument is @code{undefined},
then site ID is initialized to a random value.
@end enumerate

When site ID changes,
@erlfn{ref,erlref,classy,on_create_site,2} callback runs.

Cluster ID initialization logic is similar,
but there's no way to customize the initial value.
That has to do with the classy's requirement
that cluster IDs change to an entirely new value when site is kicked.
@code{classy:on_create_cluster/2} hook is called for the new clusters.
""".
-spec maybe_init_the_site(classy:site() | undefined) -> ok.
maybe_init_the_site(MaybeSite) ->
  maybe_init_the_site(MaybeSite, undefined).

%% This function should not be used, unless you know exactly what
%% you're doing. It's totally NOT ok to override the random cluster
%% IDs generated by classy, unless migrating an **existing** cluster
%% that had site IDs, cluster IDs and peers functioning in a manner
%% very similar to classy.
%%
%% The caller must make sure that this function is executed **exactly
%% once**, during the migration. If cluster gets set to a
%% deterministic value later, it will lead to all kinds of serious
%% problems, like node being unable to leave or join clusters.
%%
%% Hence, leaving it undocumented.
-doc false.
-spec maybe_init_the_site(classy:site() | undefined, classy:cluster_id() | undefined) -> ok.
maybe_init_the_site(MaybeSite, MaybeCluster0) ->
  {IsNewSite, Site, Ops1} = ensure_the_id(?the_site, ?on_create_site, [], MaybeSite),
  MaybeCluster = case IsNewSite of
                   true ->
                     %% Only allow overriding cluster if everything is
                     %% entirely new:
                     MaybeCluster0;
                   false ->
                     undefined
                 end,
  {IsNewCluster, _Cluster, Ops2} = ensure_the_id(?the_cluster, ?on_create_cluster, [Site], MaybeCluster),
  Ops3 = case IsNewCluster of
           true  -> [{w, ?parent_site, Site}, {w, ?joined_at, 0}];
           false -> []
         end,
  {ok, Effects} = classy_table:atomically(?tab, Ops1 ++ Ops2 ++ Ops3),
  [Fun() || Fun <- Effects],
  ok.

