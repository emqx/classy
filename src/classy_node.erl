-spec verify_hello(
        node(),
        classy:cluster_id() | any,
        classy:join_intent()
       ) -> bootstrap_info() | {error, _}.
verify_hello(Node, ExpectedCluster, Intent) ->
  maybe
    Hello = hello(Node),
    #{site := Remote, cluster := Cluster} ?= Hello,
    true ?= ExpectedCluster =:= any orelse
            Cluster =:= ExpectedCluster orelse
            {error, {cluster_changed, #{ExpectedCluster => Cluster}}},
    ok ?= classy_hook:all(?on_pre_join, [Cluster, Remote, Node, Intent]),
    Hello
  end.

-spec hello(node()) -> bootstrap_info() | {error, _}.
hello(Node) ->
  try erpc:call(Node, ?MODULE, hello, [], classy_lib:rpc_timeout()) of
    #{site := _, cluster := _, mem_data := _} = Hello ->
      Hello;
    Other ->
      {error, {bad_hello, Node, Other}}
  catch
    error:{exception, undef, _} ->
      %% Node may be old and not classy-aware. Try fallback:
      hello_fallback(Node);
    error:Err ->
      {error, Err};
    EC:Err:Stack ->
      {error, {EC, Err, Stack}}
  end.

-spec hello_fallback(node()) -> bootstrap_info() | {error, _}.
hello_fallback(Node) ->
  case the_site() of
    {ok, Local} ->
      maybe
        BootstrapNodeInfo = site_info_fallback(Node),
        {ok, Node, Site, Cluster, _SiteMeta} ?= BootstrapNodeInfo,
        {ok, PeerNodes} ?= classy_hook:first_match(?fallback_get_peer_nodes, [Node]),
        true ?= is_list(PeerNodes) orelse {error, {bad_peer_nodes, PeerNodes}},
        PeerInfo = [BootstrapNodeInfo | [site_info_fallback(I) || I <- PeerNodes, I =/= Node]],
        {ok, MemData} ?= classy_membership:mem_data_fallback(Local, Cluster, PeerInfo),
        #{ site     => Site
         , cluster  => Cluster
         , mem_data => MemData
         }
      else
        undefined ->
          {error, invalid_target_node};
        {error, _} = Error ->
          Error
      end;
    undefined ->
      {error, default_site_not_initialized}
  end.

-spec site_info_fallback(node()) -> {ok, node(), classy:site(), classy:cluster_id(), classy:site_metadata()} | {error, _}.
site_info_fallback(Node) ->
  maybe
    {ok, Site} ?= classy_hook:first_match(?fallback_get_site, [Node]),
    true ?= is_binary(Site) orelse {error, {bad_fallback_site, Site}},
    {ok, Cluster} ?= classy_hook:first_match(?fallback_get_cluster, [Node]),
    true ?= is_binary(Cluster) orelse {error, {bad_fallback_cluster, Cluster}},
    SiteMeta = classy_hook:fold(?fallback_get_meta, [Node], #{via_fallback => true}),
    true ?= is_map(SiteMeta) orelse {error, {bad_metadata, SiteMeta}},
    {ok, Node, Site, Cluster, SiteMeta}
  else
    undefined ->
      {error, invalid_target_node};
    {error, _} = Error ->
      Error
  end.

flush_mem_deltas() ->
  receive
    #cast_mem_deltas{} ->
      flush_mem_deltas()
  after 0 ->
      ok
  end.

handle_membership_change_event(
  #cast_mem_deltas{ cluster = Cluster
                  , data = Deltas
                  },
  S0 = #s{cluster = ThisCluster, site = Local}
 ) ->
  ?tp(debug, membership_change,
      #{ cluster => Cluster
       , origin => Local
       , data => Deltas
       }),
  if Cluster =:= ThisCluster ->
      case apply_deltas_with_effects(Deltas, S0) of
        {ok, S}      -> {noreply, S};
        {error, Err} -> {stop, Err, undefined}
      end;
     true ->
      %% Update from the old cluster. Ignore it.
      {noreply, S0}
  end.

-spec update_runtime(#s{}) -> #s{}.
update_runtime(S) ->
  adjust_run_level(update_sites_status(S)).

handle_kick(Target, Intent, S = #s{site = Local}) when is_binary(Local) ->
  maybe
    {ok, Cluster} ?= the_cluster(),
    ok ?= classy_hook:all(?on_pre_kick, [Cluster, Target, Intent]),
    classy_hook:foreach(?on_kick_decided, [Cluster, Target, Intent]),
    {ok, _} ?= classy_membership:set_member(Cluster, Local, Target, false),
    classy_membership:flush(Cluster, Local),
    if Target =:= Local ->
        on_leave(S, Intent);
       true ->
        {ok, S}
    end
  else
    undefined        -> {error, local_not_in_cluster};
    {error, _} = Err -> Err
  end.

-spec handle_join(#s{}, gen_server:from(), #call_join{}) -> {reply, {error, _}, #s{}} | {noreply, #s{}}.
handle_join(S, From, Call) ->
  #call_join{ node    = Node
            , cluster = ExpectedCluster
            , intent  = Intent
            } = Call,
  maybe
    ok ?= ensure_is_not_joining(S),
    ok ?= check_join_locks(Intent, S),
    %% Initial probe before taking the lock, to make sure the remote
    %% is joinable:
    #{} ?= verify_hello(Node, ExpectedCluster, Intent),
    %% Try to take the join lock on remote:
    ok ?= lock_join_remote(Node),
    %% Proceed to the next stage, which has side effects:
    handle_join1(S, From, Call)
  else
    {error, _} = Err ->
      {reply, Err, S}
  end.

-spec handle_join1(#s{}, gen_server:from(), #call_join{}) -> {reply, {error, _}, #s{}} | {noreply, #s{}}.
handle_join1(S0, From, Call) ->
  #call_join{ node    = Node
            , cluster = ExpectedCluster
            , intent  = Intent
            } = Call,
  #s{site = Local} = S0,
  maybe
    %% Get second hello, now that the remote is locked:
    Hello = verify_hello(Node, ExpectedCluster, Intent),
    #{site := Remote, cluster := Cluster, mem_data := MemData} ?= Hello,
    {ok, S1} ?= do_join_node(Node, Cluster, Remote, MemData, Intent, S0),
    case launch_post_join_child(S1, From, Cluster, Local, Node, Intent) of
      {ok, S} ->
        {noreply, S};
      {error, _} = Err ->
        unlock_join_remote(Node, self()),
        {reply, Err, S1}
    end
  else
    {error, _} = Err1 ->
      unlock_join_remote(Node, self()),
      {reply, Err1, S0}
  end.

-spec check_join_locks(classy:join_intent(), #s{}) -> ok | {error, _}.
check_join_locks(_Intent, #s{join_locks = []}) ->
  ok;
check_join_locks(Intent, #s{join_locks = [_|_]}) ->
  case lists:member(Intent, application:get_env(classy, force_intents, [])) of
    true  -> ok;
    false -> {error, retry_later}
  end.

-spec do_join_node(
        node(),
        classy:cluster_id(),
        classy:site(),
        classy_membership:sync_data(),
        classy:join_intent(),
        #s{}
       ) ->
        {ok, #s{}} | {error, _}.
do_join_node(Node, Cluster, Remote, MemData, JoinIntent, S0) ->
  {ok, Local} = the_site(),
  case the_cluster() of
    {ok, Cluster} ->
      %% Already in the same cluster with `Node'. Set our membership
      %% status and trigger re-sync (do we need to re-run hooks?):
      classy_membership:call_sync(Cluster, Local, MemData),
      %% Journal the hook invocation, so that it can be replayed if
      %% the node stops after the cluster state has been updated, but
      %% before the hook had a chance to run:
      ok = classy_table:dirty_write(
             ?tab, ?pending_on_join_hook, {Cluster, Local, Node, JoinIntent}),
      ok = classy_table:flush(?tab),
      {ok, Clock} = classy_membership:set_member(Cluster, Local, Local, true),
      classy_membership:flush(Cluster, Local),
      ok = classy_table:write(?tab, ?joined_at, Clock),
      {ok, update_runtime(S0)};
    {ok, OldCluster} when OldCluster =/= Cluster ->
      %% Site is currently in a different cluster. Leave it first:
      LeaveIntent = {join, #{node => Node, cluster => Cluster, join_intent => JoinIntent}},
      case handle_kick(Local, LeaveIntent, S0) of
        {ok, S} ->
          do_join_node(Node, Cluster, Remote, MemData, JoinIntent, S);
        Err ->
          Err
      end;
     undefined ->
      %% Site is not in any cluster:
      {ok, S} = join_cluster(Cluster, Node, Local, Remote, JoinIntent, S0),
      do_join_node(Node, Cluster, Remote, MemData, JoinIntent, S)
  end.

on_leave(S = #s{cluster = Cluster, site = Local}, Intent) ->
  %% Trigger some of the events related to the old cluster:
  foreach_site_info(
    fun(Peer, _) ->
        update_site_info(false, Peer, undefined, S)
    end),
  %% Sync with the business apps:
  to_stopped(leave),
  {ok, _} = classy_table:atomically(
              ?tab,
              [ {d, ?the_cluster}
              , {d, ?joined_at}
              , {d, ?pending_on_join_hook}
              ]),
  classy_hook:foreach(?on_leave, [Cluster, Local, Intent]),
  classy_table:clear(?site_info),
  case Intent of
    {join, _} ->
      {ok, S#s{cluster = undefined}};
    _ ->
      %% maybe_initialize_after_leave hook should've created cluster.
      %% Preserve the post-join bookkeeping in the new state, so that
      %% the 'EXIT' message of an aborted hook child is still handled:
      {ok, S1} = init_cluster(),
      {ok, S1#s{post_join = S#s.post_join}}
  end.

-spec join_cluster(classy:cluster_id(), node(), classy:site(), classy:site(), classy:join_intent(), #s{}) -> {ok, #s{}}.
join_cluster(Cluster, JoinToNode, Local, Remote, Intent, S = #s{}) ->
  %% Deal with the situation when re-joining the same cluster. We need
  %% to restart everything from scratch.
  %%
  %% 1. Wipe data for the cluster (it should be running):
  {ok, OldPid} = classy_sup:ensure_membership(Cluster, Local),
  ok = classy_membership:wipe(Cluster, Local, true),
  %% 2. Flush any deltas from the old process that could be stored in the mailbox:
  flush_mem_deltas(),
  %% 3. Restart membership from scratch:
  {ok, NewPid} = classy_sup:ensure_membership(Cluster, Local),
  true = OldPid =/= NewPid, % assert
  %% Log the join synchronously, before the cluster id is committed
  %% (the application hooks run asynchronously at a later point):
  ?tp(notice, classy_joined_cluster,
      #{ cluster        => Cluster
       , local          => Local
       , joined_to_node => JoinToNode
       , intent         => Intent
       }),
  classy_table:dirty_write(?tab, ?the_cluster, Cluster),
  classy_table:dirty_write(?tab, ?parent_site, Remote),
  classy_table:flush(?tab),
  {ok, S#s{cluster = Cluster}}.

-spec run_post_join_hooks(classy:cluster_id(), classy:site(), node() | undefined, classy:join_intent()) -> ok.
run_post_join_hooks(Cluster, Local, JoinToNode, Intent) ->
  classy_hook:foreach(?on_post_join, [Cluster, Local, JoinToNode, Intent]),
  {ok, _} = classy_table:atomically(?tab, [{d, ?pending_on_join_hook}]),
  ok.

-spec ensure_is_not_joining(#s{}) -> ok | {error, node_is_joining_other}.
ensure_is_not_joining(#s{post_join = #post_join{}}) ->
  {error, node_is_joining_other};
ensure_is_not_joining(#s{}) ->
  ok.

-spec abort_post_join_hooks(#s{}) -> #s{}.
abort_post_join_hooks(S = #s{post_join = undefined}) ->
  S;
abort_post_join_hooks(S = #s{post_join = #post_join{worker = Pid}}) ->
  _ = classy_sup:terminate_dynamic_child(?post_join_child),
  %% Flush link messages:
  receive
    {'EXIT', Pid, _} -> ok
  after 0 ->
      ok
  end,
  finalize_join({error, aborted}, S).

-spec launch_post_join_child(
        #s{},
        gen_server:from() | undefined,
        classy:cluster_id(),
        classy:site(),
        node() | undefined,
        classy:join_intent()
       ) ->
        {ok, #s{}} | {error, _}.
launch_post_join_child(S, From, Cluster, Local, JoinToNode, Intent) ->
  IsReplay = From =:= undefined,
  Spec = #{ id       => ?post_join_child
          , start    => {?MODULE, start_link_post_join, [self(), IsReplay, Cluster, Local, JoinToNode, Intent]}
          , restart  => temporary
          , type     => worker
          },
  case classy_sup:ensure_dynamic_child(Spec) of
    {ok, Pid} ->
      PJ = #post_join{node = JoinToNode, worker = Pid, reply = From},
      {ok, S#s{post_join = PJ}};
    {error, Reason} = Err ->
      logger:error("Failed to start the post-join hooks: ~p", [Reason]),
      Err
  end.

%% Handle reply from the async post-join worker:
-spec finalize_join(_Reason, #s{}) -> #s{}.
finalize_join(Reason, S0 = #s{post_join = PJ}) ->
  #post_join{node = Node, reply = From} = PJ,
  Result = case Reason of
             normal ->
               ok;
             {error, aborted} = Aborted ->
               Aborted;
             _ ->
               ?tp(error, "Post-join hooks crashed",
                   #{ reason => Reason
                    , remote => Node
                    }),
               {error, post_join_failed}
           end,
  S = S0#s{post_join = undefined},
  case From of
    undefined ->
      %% This is replay. No need to release locks, as the original
      %% process that took them is dead:
      S;
    _ ->
      gen_server:reply(From, Result),
      unlock_join_remote(Node, self()),
      S
  end.

-doc false.
-spec start_link_post_join(
        pid(),
        boolean(),
        classy:cluster_id(),
        classy:site(),
        node() | undefined,
        classy:join_intent()
       ) -> {ok, pid()}.
start_link_post_join(Parent, IsReplay, Cluster, Local, JoinToNode, Intent) ->
  proc_lib:start_link(
    ?MODULE,
    post_join_child,
    [Parent, IsReplay, Cluster, Local, JoinToNode, Intent]).

-spec post_join_child(
        pid(),
        boolean(),
        classy:cluster_id(),
        classy:site(),
        node() | undefined,
        classy:join_intent()
       ) -> no_return().
post_join_child(Parent, IsReplay, Cluster, Local, JoinToNode, Intent) ->
  erlang:link(Parent),
  proc_lib:init_ack({ok, self()}),
  ?tp(notice, classy_post_join_hooks,
      #{ phase   => start
       , cluster => Cluster
       , replay  => IsReplay
       , intent  => Intent
       }),
  ok = run_post_join_hooks(Cluster, Local, JoinToNode, Intent),
  ?tp(notice, classy_post_join_hooks,
      #{ phase   => complete
       , cluster => Cluster
       , replay  => IsReplay
       , intent  => Intent
       }),
  exit(normal).

-spec maybe_replay_pending_on_join_hook(#s{}) -> {ok, #s{}}.
maybe_replay_pending_on_join_hook(S0) ->
  maybe
    %% FIXME: make it a map:
    [{Cluster, Local, JoinToNode, Intent}] ?= classy_table:lookup(?tab, ?pending_on_join_hook),
    ?tp(warning, "Replaying pending post-join hooks",
        #{ cluster => Cluster
         , node => JoinToNode
         , intent => Intent
         }),
    {ok, S} ?= launch_post_join_child(S0, undefined, Cluster, Local, JoinToNode, Intent),
    {ok, S}
  else
    _ -> {ok, S0}
  end.

%% Update node tracking information
-spec update_sites_status(#s{}) -> #s{}.
update_sites_status(S) ->
  foreach_site_info(
    fun(Peer, SiteInfo) ->
        update_site_info(true, Peer, SiteInfo, S)
    end),
  ok = classy_table:flush(?site_info),
  classify(),
  S.

init_cluster() ->
  maybe
    {ok, Cluster} ?= the_cluster(),
    {ok, Site} ?= the_site(),
    logger:update_process_metadata(#{local => Site}),
    {ok, _} = classy_sup:ensure_membership(Cluster, Site),
    start_old_clusters(Site),
    S = update_runtime(
          #s{ cluster = Cluster
            , site = Site
            }),
    ?tp(debug, classy_init_clustering, #{local => Site, cluster => Cluster}),
    {ok, S}
  else
    _ ->
      {error, default_site_not_initialized}
  end.

-spec ensure_the_id(?the_cluster | ?the_site, ?on_create_cluster | ?on_create_site, list(), binary() | undefined) ->
        { boolean()
        , binary()
        , [classy_table:atomic_op(fun(() -> _))]
        }.
ensure_the_id(Key, OnCreateHook, HookArgs, Default) ->
  case classy_table:lookup(?tab, Key) of
    [Bin] when is_binary(Bin) ->
      {false, Bin, []};
    [] ->
      case Default of
        undefined ->
          NRandBytes = application:get_env(classy, rand_id_bytes, 16),
          true = is_integer(NRandBytes) andalso NRandBytes > 0, %% assert
          Val = base64:encode(crypto:strong_rand_bytes(NRandBytes), #{padding => false, mode => urlsafe});
        Val when is_binary(Val) ->
          ok
      end,
      { true
      , Val
      , [ {w, Key, Val}
        , {then, fun() ->
                     classy_hook:foreach(OnCreateHook, [Val | HookArgs])
                 end}
        ]
      }
  end.

%% NOTE: must be called after `classify':
-spec adjust_run_level(#s{}) -> #s{}.
adjust_run_level(S) ->
  %% Manage cluster barrier:
  ClusterBarrier = cluster,
  NKnown = length(intersection(classy_lib:to_cluster_sets())),
  NSites = classy_lib:n_sites(),
  case NKnown >= NSites of
    true  ->
      classy_boot:rm_barrier(ClusterBarrier);
    false ->
      classy_boot:set_barrier(
        ClusterBarrier,
        ?classy_rl_cluster - 1,
        [async, {hint, << "Waiting for "
                        , (integer_to_binary(NKnown))/binary
                        , "/"
                        , (integer_to_binary(NSites))/binary
                        , " known sites"
                       >>}])
  end,
  %% Manage quorum barrier:
  QuorumBarrier = quorum,
  NConnected = length(intersection(classy_lib:quorum_sets())),
  Quorum = classy:quorum(config),
  case NConnected >= Quorum of
    true  ->
      classy_boot:rm_barrier(QuorumBarrier);
    false ->
      classy_boot:set_barrier(
        QuorumBarrier,
        ?classy_rl_quorum - 1,
        [async, {hint, << "Waiting for "
                        , (integer_to_binary(NConnected))/binary
                        , "/"
                        , (integer_to_binary(Quorum))/binary
                        , " running quorum nodes"
                       >>}])
  end,
  classy_boot:ensure_started(),
  S.

%% Start membership processes for all known former clusters, in order
%% to relay information to former peers.
start_old_clusters(Site) ->
  maps:foreach(
    fun(Cluster, Peers) ->
        case Peers -- [Site] of
          []      -> ok;
          [_ | _] -> classy_sup:ensure_membership(Cluster, Site)
        end
    end,
    classy_membership:known_clusters(Site)).

to_stopped(Reason) ->
  prep_stop(Reason),
  classy_boot:stop_system().

